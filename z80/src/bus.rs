/// Everything the Z80 sees around it: memory, I/O ports and interrupt lines.
///
/// Implemented by each system (Game Gear, CP/M test harness, ...).
/// The CPU only calls these methods; it never knows what is behind them.
pub trait Z80Bus {
    /// Returns the byte stored at `address` in memory space.
    fn read(&self, address: u16) -> u8;

    /// Stores `value` at `address` in memory space.
    fn write(&mut self, address: u16, value: u8);

    /// Returns the byte provided by the device mapped on `port` (IN instructions).
    ///
    /// Mutable because reading a port can update the peripheral state
    /// (e.g. reading the VDP status port acknowledges its interrupt).
    /// The full 16-bit port address is given; the high byte comes from
    /// A or B depending on the instruction. Systems may ignore it.
    fn io_read(&mut self, port: u16) -> u8;

    /// Sends `value` to the device mapped on `port` (OUT instructions).
    fn io_write(&mut self, port: u16, value: u8);

    /// Returns `true` while a maskable interrupt is requested.
    ///
    /// Level-triggered: must keep returning `true` until the device is
    /// acknowledged. The CPU checks it at the end of each instruction and
    /// ignores it while interrupts are disabled (IFF1 = 0).
    ///
    /// Hardware: INT pin (input, active low). Generated by I/O devices,
    /// honored at the end of the current instruction if IFF is enabled.
    fn int_active(&self) -> bool {
        false
    }

    /// Returns `true` once if a non-maskable interrupt occurred since the
    /// last call, and clears it.
    ///
    /// Edge-triggered: the implementation must latch the event and report
    /// it exactly once. Calling this method consumes the event.
    ///
    /// Hardware: NMI pin (input, negative edge-triggered). Higher priority
    /// than INT, always recognized at the end of the current instruction
    /// regardless of IFF, and forces a restart at 0x0066.
    fn take_nmi(&mut self) -> bool {
        false
    }
}
